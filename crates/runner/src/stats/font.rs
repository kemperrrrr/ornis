//! Tiny built-in 5×7 bitmap font for the stats window: digits, upper-case
//! Latin letters and the few symbols the panel prints. Lower-case input
//! is folded to upper case; unknown characters draw as a blank cell.

/// Glyph cell width in font pixels (5 columns + 1 spacing).
pub const ADVANCE: u32 = 6;
/// Glyph width in font pixels (bit `WIDTH - 1` is the leftmost column).
pub const WIDTH: u32 = 5;
/// Glyph height in font pixels.
pub const HEIGHT: u32 = 7;

/// Row bitmaps (bit 4 = leftmost column) of `ch`, or `None` for a blank.
pub fn glyph(ch: char) -> Option<[u8; 7]> {
    let ch = ch.to_ascii_uppercase();
    GLYPHS.iter().find(|(c, _)| *c == ch).map(|(_, rows)| *rows)
}

