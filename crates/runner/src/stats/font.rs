#[cfg(test)]
mod tests {
    use super::glyph;

    #[test]
    fn folds_case_and_blanks_unknown() {
        assert_eq!(glyph('a'), glyph('A'));
        assert!(glyph('0').is_some());
        assert_eq!(glyph(' '), None);
        assert_eq!(glyph('€'), None);
    }
}
